"""Generate the RaceUI terminal logo icon (ANSI truecolor half-blocks) from the PNG logo.

Usage: python scripts/generate-logo.py
Writes src/cli/logo-data.ts. Run again whenever assets/raceui-logo.png changes.
The wordmark ("RACEUI") is drawn as block text in src/cli/logo.ts.
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "raceui-logo.png"
OUT = ROOT / "src" / "cli" / "logo-data.ts"
ROWS = 9  # terminal rows (each holds two pixel rows)
ICON_RIGHT_EDGE = 0.40  # the browser icon occupies the left ~40% of the logo
DARK_REPLACEMENT = (139, 149, 161)  # frame colour readable on light and dark terminals


def is_bg(px):
    return px[0] > 225 and px[1] > 225 and px[2] > 225


def recolor(px):
    if px[0] < 70 and px[1] < 70 and px[2] < 70:
        return DARK_REPLACEMENT
    return px[:3]


def main():
    img = Image.open(SRC).convert("RGB")
    w, h = img.size
    img = img.crop((0, 0, int(w * ICON_RIGHT_EDGE), h))
    pix = img.load()
    xs, ys = [], []
    for y in range(0, img.size[1], 2):
        for x in range(0, img.size[0], 2):
            if not is_bg(pix[x, y]):
                xs.append(x)
                ys.append(y)
    img = img.crop((min(xs), min(ys), max(xs) + 1, max(ys) + 1))
    cw, ch = img.size
    prow = ROWS * 2
    width = round(prow * cw / ch * 0.5 * 2)  # terminal cells are ~2x taller than wide
    img = img.resize((width, prow), Image.LANCZOS)
    pix = img.load()

    esc = "\x1b"
    color_lines, plain_lines = [], []
    for y in range(0, prow, 2):
        line, plain = "", ""
        for x in range(width):
            top, bot = pix[x, y], pix[x, y + 1]
            tb, bb = is_bg(top), is_bg(bot)
            t, b = recolor(top), recolor(bot)
            if tb and bb:
                line += f"{esc}[0m "
                plain += " "
            elif not tb and bb:
                line += f"{esc}[0m{esc}[38;2;{t[0]};{t[1]};{t[2]}m▀"
                plain += "▀"
            elif tb and not bb:
                line += f"{esc}[0m{esc}[38;2;{b[0]};{b[1]};{b[2]}m▄"
                plain += "▄"
            else:
                line += f"{esc}[38;2;{t[0]};{t[1]};{t[2]}m{esc}[48;2;{b[0]};{b[1]};{b[2]}m▀"
                plain += "█"
        color_lines.append(line + f"{esc}[0m")
        plain_lines.append(plain)

    body = "// Generated by scripts/generate-logo.py from assets/raceui-logo.png. Do not edit by hand.\n"
    body += f"export const ICON_WIDTH = {width};\n\n"
    body += "export const ICON_COLOR: string[] = [\n" + "".join(f'  "{l}",\n' for l in color_lines) + "];\n\n"
    body += "export const ICON_PLAIN: string[] = [\n" + "".join(f'  "{l}",\n' for l in plain_lines) + "];\n"
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({width}x{ROWS})")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(plain_lines))


if __name__ == "__main__":
    main()
